def _client() -> anthropic.AsyncAnthropic:
    if settings.anthropic_api_key:
        return anthropic.AsyncAnthropic(api_key=settings.anthropic_api_key)
    return anthropic.AsyncAnthropic()


def _gemini_client() -> genai.Client:
    if not settings.gemini_api_key:
        raise PlantCareUnavailable("Servizio AI non configurato.")
    return genai.Client(api_key=settings.gemini_api_key)


_NO_SHEET = "Impossibile generare la scheda per questa richiesta."


async def generate_sheet(*, species_hint: Optional[str], symptoms: Optional[str], photo: Optional[Photo]) -> dict:
    """Returns a dict matching _SHEET_SCHEMA, written by settings.ai_provider.
    Raises PlantCareUnavailable."""
    if species_hint:
        intro = f"Specie: {species_hint}."
    else:
        intro = "Specie: non indicata, riconoscila dalla foto."
    text = f"{intro}\n\n<sintomi>\n{symptoms or 'Nessuna descrizione fornita.'}\n</sintomi>\n\nPrepara la scheda di recupero."

    if settings.ai_provider == "gemini":
        raw = await _generate_with_gemini(text, photo)
    else:
        raw = await _generate_with_anthropic(text, photo)
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        logger.error("AI returned invalid JSON: %s", raw[:200])
        raise PlantCareUnavailable(_NO_SHEET) from exc


async def _generate_with_gemini(text: str, photo: Optional[Photo]) -> str:
    contents: list = []
    if photo is not None:
        contents.append(genai_types.Part.from_bytes(data=photo.data, mime_type=photo.media_type))
    contents.append(text)

    client = _gemini_client()
    config = genai_types.GenerateContentConfig(
        system_instruction=_SYSTEM_PROMPT,
        response_mime_type="application/json",
        response_json_schema=_SHEET_SCHEMA,
    )
    # Free-tier traffic is the first to get "high demand" 503s, and quotas
    # (429) are per model: on either, try the fallback model once.
    models = [settings.gemini_model]
    if settings.gemini_fallback_model and settings.gemini_fallback_model != settings.gemini_model:
        models.append(settings.gemini_fallback_model)

    for i, model in enumerate(models):
        try:
            response = await client.aio.models.generate_content(model=model, contents=contents, config=config)
            break
        except genai_errors.APIError as exc:
            if exc.code in (429, 503) and i + 1 < len(models):
                logger.warning("Gemini %s returned %s, falling back to %s", model, exc.code, models[i + 1])
                continue
            if exc.code == 429:  # free-tier quota (per minute or per day)
                logger.warning("Gemini quota exceeded: %s", exc)
                raise PlantCareUnavailable("Limite di richieste gratuite raggiunto, riprova più tardi.") from exc
            logger.error("Gemini API error %s: %s", exc.code, exc)
            raise PlantCareUnavailable("Servizio AI non disponibile al momento.") from exc
        except httpx.HTTPError as exc:
            logger.error("Gemini connection error: %s", exc)
            raise PlantCareUnavailable("Servizio AI non raggiungibile al momento.") from exc

    candidate = response.candidates[0] if response.candidates else None
    if candidate is None or candidate.finish_reason != genai_types.FinishReason.STOP or not response.text:
        # Blocked by safety filters, or truncated (MAX_TOKENS): no usable JSON.
        logger.warning(
            "Gemini stopped with %s (prompt feedback: %s)",
            candidate.finish_reason if candidate else None,
            response.prompt_feedback,
        )
        raise PlantCareUnavailable(_NO_SHEET)
    return response.text


async def _generate_with_anthropic(text: str, photo: Optional[Photo]) -> str:
    content: list = []
    if photo is not None:
        content.append({
            "type": "image",
            "source": {
                "type": "base64",
                "media_type": photo.media_type,
                "data": base64.standard_b64encode(photo.data).decode("ascii"),
            },
        })
    content.append({"type": "text", "text": text})

    try:
        client = _client()
        response = await client.beta.messages.create(
            model=settings.anthropic_model,
            max_tokens=16000,
            system=_SYSTEM_PROMPT,
            messages=[{"role": "user", "content": content}],
            output_config={"effort": "medium", "format": {"type": "json_schema", "schema": _SHEET_SCHEMA}},
            # On a safety-classifier decline, retry server-side on the model
            # Anthropic recommends for that refusal category.
            betas=["server-side-fallback-2026-07-01"],
            fallbacks="default",
        )
    except anthropic.RateLimitError as exc:
        logger.warning("Claude rate limit: %s", exc)
        raise PlantCareUnavailable("Servizio momentaneamente sovraccarico, riprova tra poco.") from exc
    except anthropic.APIStatusError as exc:
        logger.error("Claude API error %s: %s", exc.status_code, exc.message)
        raise PlantCareUnavailable("Servizio AI non disponibile al momento.") from exc
    except anthropic.APIConnectionError as exc:
        logger.error("Claude connection error: %s", exc)
        raise PlantCareUnavailable("Servizio AI non raggiungibile al momento.") from exc
    except anthropic.AnthropicError as exc:  # e.g. no credentials configured
        logger.error("Claude client error: %s", exc)
        raise PlantCareUnavailable("Servizio AI non configurato.") from exc

    if response.stop_reason != "end_turn":
        # "refusal" (whole fallback chain declined) or "max_tokens" (JSON
        # would be truncated) — either way there's no usable sheet.
        logger.warning("Claude stopped with %s", response.stop_reason)
        raise PlantCareUnavailable(_NO_SHEET)

    raw = next((b.text for b in response.content if b.type == "text"), None)
    if raw is None:
        raise PlantCareUnavailable(_NO_SHEET)
    return raw
