class PlantCareUnavailable(Exception):
    """The AI provider couldn't produce a sheet (not configured, down,
    rate-limited, refused...). The router turns this into a 503."""


@dataclass
class Identification:
    scientific_name: str
    common_name: Optional[str]
    score: float


@dataclass
class Photo:
    data: bytes
    media_type: str


# ---------------------------------------------------------------------------
# Species identification (PlantNet)
# ---------------------------------------------------------------------------

async def identify_with_plantnet(photo: Photo) -> Optional[Identification]:
    """Best PlantNet match, or None when PlantNet isn't configured, finds
    nothing, or fails. Never raises: the AI provider identifies the plant instead."""
    if not settings.plantnet_api_key:
        return None
    try:
        async with httpx.AsyncClient(timeout=20.0) as client:
            r = await client.post(
                PLANTNET_IDENTIFY_URL,
                params={"api-key": settings.plantnet_api_key, "lang": "it", "nb-results": 1},
                files={"images": ("photo", photo.data, photo.media_type)},
                data={"organs": "auto"},
            )
    except httpx.HTTPError as exc:
        logger.warning("PlantNet request failed: %s", exc)
        return None

    if r.status_code == 404:  # PlantNet's "Species not found"
        return None
    if r.status_code != 200:
        logger.warning("PlantNet returned %s: %s", r.status_code, r.text[:200])
        return None

    results = r.json().get("results") or []
    if not results:
        return None
    best = results[0]
    if best.get("score", 0.0) < settings.plantnet_min_score:
        return None
    species = best.get("species") or {}
    common_names = species.get("commonNames") or []
    return Identification(
        scientific_name=species.get("scientificNameWithoutAuthor", ""),
        common_name=common_names[0] if common_names else None,
        score=float(best["score"]),
    )


