"""
AI "scheda di recupero pianta": given a species picked from a fixed
catalog and/or a photo, produce an orientative recovery sheet.

Pipeline:
  1. Species: the catalog choice wins if given. Otherwise, with a photo and
     a PLANTNET_API_KEY configured, PlantNet identifies it; without a key
     (or with a low-confidence match) the AI provider identifies it from the photo.
  2. Text: generated by the configured AI_PROVIDER — Gemini (free tier) or
     Claude — as structured JSON, with the photo attached when there is one
     so it can also judge visible damage.

The disclaimer is a fixed server-side string added to every response by
the router — never left to the model, so it can't be dropped or reworded.
Swapping PlantNet for a self-hosted model (PyTorch/TensorFlow) later only
means replacing identify_with_plantnet(); callers depend on Identification.
"""
